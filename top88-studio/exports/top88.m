%%%% AN 88 LINE TOPOLOGY OPTIMIZATION CODE Nov, 2010 %%%%
function top88(nelx,nely,volfrac,penal,rmin,ft)
% Configured by MATLAB TopOpt Configurator & Exporter.
% Save as top88.m. Run top88() or the generated six-argument command.
% Mesh coordinates are compiled below; regenerate to change the mesh.
% volfrac applies to available cells. Passive cells retain Emin stiffness.
% Check disconnected-component stability and conditioning in MATLAB.
if nargin == 0
  nelx = 60;
  nely = 30;
  volfrac = 0.5;
  penal = 3;
  rmin = 1.5;
  ft = 1;
elseif nargin ~= 6
  error('FORM:Arguments','Use top88() or top88(nelx,nely,volfrac,penal,rmin,ft).');
end
if ~(isnumeric(nelx) && isreal(nelx) && isscalar(nelx) && isfinite(nelx) && ...
     isnumeric(nely) && isreal(nely) && isscalar(nely) && isfinite(nely) && ...
     nelx == 60 && nely == 30)
  error('FORM:Mesh','This export requires nelx=60 and nely=30. Regenerate for another mesh.');
end
if ~(isnumeric(volfrac) && isreal(volfrac) && isscalar(volfrac) && isfinite(volfrac) && ...
     volfrac >= 0.05 && volfrac <= 1)
  error('FORM:Parameters','volfrac must be a finite real scalar between 0.05 and 1.');
end
if ~(isnumeric(penal) && isreal(penal) && isscalar(penal) && isfinite(penal) && ...
     penal >= 1 && penal <= 6)
  error('FORM:Parameters','penal must be a finite real scalar between 1 and 6.');
end
if ~(isnumeric(rmin) && isreal(rmin) && isscalar(rmin) && isfinite(rmin) && ...
     rmin >= 1 && rmin <= 10)
  error('FORM:Parameters','rmin must be a finite real scalar between 1 and 10.');
end
if ~(isnumeric(ft) && isreal(ft) && isscalar(ft) && isfinite(ft) && ismember(ft,[1 2]))
  error('FORM:Parameters','ft must be 1 (sensitivity) or 2 (density).');
end
% Use floating-point arithmetic even when called with integer numeric inputs.
nelx = double(nelx);
nely = double(nely);
volfrac = double(volfrac);
penal = double(penal);
rmin = double(rmin);
ft = double(ft);
%% MATERIAL PROPERTIES
E0 = 1;
Emin = 1e-9;
nu = 0.3;
%% PREPARE FINITE ELEMENT ANALYSIS
A11 = [12  3 -6 -3;  3 12  3  0; -6  3 12 -3; -3  0 -3 12];
A12 = [-6 -3  0  3; -3 -6 -3 -6;  0 -3 -6  3;  3 -6  3 -6];
B11 = [-4  3 -2  9;  3 -4 -9  4; -2 -9 -4 -3;  9  4 -3 -4];
B12 = [ 2 -3  4 -9; -3  2  9 -2;  4  9  2  3; -9 -2  3  2];
KE = 1/(1-nu^2)/24*([A11 A12;A12' A11]+nu*[B11 B12;B12' B11]);
nodenrs = reshape(1:(1+nelx)*(1+nely),1+nely,1+nelx);
edofVec = reshape(2*nodenrs(1:end-1,1:end-1)+1,nelx*nely,1);
edofMat = repmat(edofVec,1,8)+repmat([0 1 2*nely+[2 3 0 1] -2 -1],nelx*nely,1);
iK = reshape(kron(edofMat,ones(8,1))',64*nelx*nely,1);
jK = reshape(kron(edofMat,ones(1,8))',64*nelx*nely,1);
% DEFINE LOADS AND SUPPORTS (generated by FORM)
% Coordinates: x right, row y down; positive Fy is upward.
ndof = 2*(nelx+1)*(nely+1);
F = sparse(ndof,1);
U = zeros(ndof,1);
% L1: mesh node (60, 15)
n = 60*(nely+1)+15+1;
F(2*n-1) = F(2*n-1) + (0);
F(2*n) = F(2*n) + (-1);
fixeddofs = [];
[sx,sy] = meshgrid(0:0,0:30);
sn = sx(:)*(nely+1)+sy(:)+1;
fixeddofs = [fixeddofs; 2*sn-1];
fixeddofs = [fixeddofs; 2*sn];
fixeddofs = unique(fixeddofs);
alldofs = 1:ndof;
freedofs = setdiff(alldofs,fixeddofs);
%% PREPARE FILTER
iH = ones(nelx*nely*(2*(ceil(rmin)-1)+1)^2,1);
jH = ones(size(iH));
sH = zeros(size(iH));
k = 0;
for i1 = 1:nelx
  for j1 = 1:nely
    e1 = (i1-1)*nely+j1;
    for i2 = max(i1-(ceil(rmin)-1),1):min(i1+(ceil(rmin)-1),nelx)
      for j2 = max(j1-(ceil(rmin)-1),1):min(j1+(ceil(rmin)-1),nely)
        e2 = (i2-1)*nely+j2;
        k = k+1;
        iH(k) = e1;
        jH(k) = e2;
        sH(k) = max(0,rmin-sqrt((i1-i2)^2+(j1-j2)^2));
      end
    end
  end
end
H = sparse(iH,jH,sH);
Hs = sum(H,2);
%% INITIALIZE ITERATION
passive = false(nely,nelx);
active = ~passive;
targetVolume = volfrac*nnz(active);
x = volfrac*ones(nely,nelx);
x(passive) = 0;
if ft == 1
  xPhys = x;
elseif ft == 2
  xPhys = reshape((H*x(:))./Hs,nely,nelx);
end
xPhys(passive) = 0;
loop = 0;
change = 1;
%% START ITERATION
while change > 0.01
  loop = loop + 1;
  %% FE-ANALYSIS
  sK = reshape(KE(:)*(Emin+xPhys(:)'.^penal*(E0-Emin)),64*nelx*nely,1);
  K = sparse(iK,jK,sK); K = (K+K')/2;
  U(freedofs) = K(freedofs,freedofs)\F(freedofs);
  %% OBJECTIVE FUNCTION AND SENSITIVITY ANALYSIS
  ce = reshape(sum((U(edofMat)*KE).*U(edofMat),2),nely,nelx);
  c = sum(sum((Emin+xPhys.^penal*(E0-Emin)).*ce));
  dc = -penal*(E0-Emin)*xPhys.^(penal-1).*ce;
  dv = ones(nely,nelx);
  %% FILTERING/MODIFICATION OF SENSITIVITIES
  % Mask physical derivatives BEFORE the density-filter chain rule.
  dc(passive) = 0;
  dv(passive) = 0;
  if ft == 1
    dc(:) = H*(x(:).*dc(:))./Hs./max(1e-3,x(:));
  elseif ft == 2
    dc(:) = H*(dc(:)./Hs);
    dv(:) = H*(dv(:)./Hs);
  end
  %% OPTIMALITY CRITERIA UPDATE OF DESIGN VARIABLES AND PHYSICAL DENSITIES
  l1 = 0;
  % Scale the upper bracket so large load sensitivities remain feasible.
  l2 = max(1e9,max(-dc(active)./dv(active)));
  move = 0.2;
  % Bound the search when the volume constraint is inactive (e.g. volfrac = 1).
  ocIterations = 0;
  while (l2-l1)/max(l1+l2,eps) > 1e-3 && ocIterations < 100
    ocIterations = ocIterations+1;
    lmid = 0.5*(l2+l1);
    xnew = zeros(nely,nelx);
    % Update only available variables; avoid 0/0 on frozen passive cells.
    xnew(active) = max(0,max(x(active)-move,min(1,min(x(active)+move, ...
      x(active).*sqrt(-dc(active)./dv(active)/lmid)))));
    xnew(passive) = 0;
    if ft == 1
      xPhys = xnew;
    elseif ft == 2
      xPhys(:) = (H*xnew(:))./Hs;
    end
    % Enforce voids AFTER filtering, inside EVERY volume bisection.
    xPhys(passive) = 0;
    if sum(xPhys(:)) > targetVolume
      l1 = lmid;
    else
      l2 = lmid;
    end
  end
  change = max(abs(xnew(:)-x(:)));
  x = xnew;
  %% PRINT RESULTS
  fprintf(' It.:%5i Obj.:%11.4f Vol.:%7.3f ch.:%7.3f\n',loop,c, ...
    mean(xPhys(:)),change);
  %% PLOT DENSITIES
  colormap(gray); imagesc(1-xPhys); caxis([0 1]); axis equal; axis off; drawnow;
end
